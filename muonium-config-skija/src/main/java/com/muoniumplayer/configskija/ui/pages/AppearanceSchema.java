    public static boolean searchMatches(String text, String query, int distance) {
        String t = text.toLowerCase(Locale.ROOT), q = query.toLowerCase(Locale.ROOT);
        if (t.contains(q)) return true;
        int d = (int) Geometry.clamp(distance, 0, 10);
        if (d == 0) return false;
        if (levenshtein(t, q, d) <= d) return true;
        for (String word : t.split("[ ._\\-/]"))
            if (!word.isEmpty() && levenshtein(word, q, d) <= d) return true;
        return false;
    }

    private static int levenshtein(String a, String b, int cap) {
        if (a.equals(b)) return 0;
        if (a.isEmpty()) return b.length();
        if (b.isEmpty()) return a.length();
        if (Math.abs(a.length() - b.length()) > cap) return cap + 1;
        int[] prev = new int[b.length() + 1], curr = new int[b.length() + 1];
        for (int j = 0; j < prev.length; j++) prev[j] = j;
        for (int i = 1; i <= a.length(); i++) {
            curr[0] = i;
            int least = i;
            for (int j = 1; j <= b.length(); j++) {
                curr[j] =
                        Math.min(
                                Math.min(prev[j] + 1, curr[j - 1] + 1),
                                prev[j - 1] + (a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1));
                least = Math.min(least, curr[j]);
            }
            if (least > cap) return cap + 1;
            int[] swap = prev;
            prev = curr;
            curr = swap;
        }
        return prev[b.length()];
    }
