package com.muoniumplayer.core.rendering.texture;

import lombok.Getter;
import com.muoniumplayer.compat.gl.GL11;
import com.muoniumplayer.core.MuoniumPlayerExtension;
import com.muoniumplayer.core.interfaces.SharedConstants;
import com.muoniumplayer.core.rendering.TextureUtil;
import com.muoniumplayer.core.rendering.rendersystem.RenderSystem;
import com.muoniumplayer.core.utils.other.multithreading.MultiThreadingUtil;

public abstract class AbstractTexture implements ITextureObject, SharedConstants {
    protected int glTextureId = -1;
    protected boolean blur;
    protected boolean mipmap;
    protected boolean blurLast;
    protected boolean mipmapLast;

    public void setBlurMipmapDirect(boolean blur, boolean mipmap) {
        this.blur = blur;
        this.mipmap = mipmap;
        int minFilter;
        int magFilter;

        if (blur) {
            minFilter = mipmap ? GL11.GL_LINEAR_MIPMAP_LINEAR : GL11.GL_LINEAR;
            magFilter = GL11.GL_LINEAR;
        } else {
            minFilter = mipmap ? GL11.GL_NEAREST_MIPMAP_LINEAR : GL11.GL_NEAREST;
            magFilter = GL11.GL_NEAREST;
        }

        this.bindTexture();
        GL11.glTexParameteri(GL11.GL_TEXTURE_2D, GL11.GL_TEXTURE_MIN_FILTER, minFilter);
        GL11.glTexParameteri(GL11.GL_TEXTURE_2D, GL11.GL_TEXTURE_MAG_FILTER, magFilter);
    }

    public void setBlurMipmap(boolean blur, boolean mipmap) {

        if (blur != this.blurLast || mipmap != this.mipmapLast) {
            this.setBlurMipmapDirect(blur, mipmap);
        }

        this.blurLast = this.blur;
        this.mipmapLast = this.mipmap;
    }

    public void restoreLastBlurMipmap() {
        this.setBlurMipmapDirect(this.blurLast, this.mipmapLast);
    }

    public int getGlTextureId() {
        if (this.glTextureId == -1) {
            this.glTextureId = TextureUtil.glGenTextures();
        }

        return this.glTextureId;
    }

    @Getter
    private FilterState filterState = FilterState.NEAREST;

    @Override
    public void linearFilter() {

        if (this.filterState != FilterState.LINEAR) {
            this.filterState = FilterState.LINEAR;
            RenderSystem.linearFilter();
        }

    }

    @Override
    public void nearestFilter() {

        if (this.filterState != FilterState.NEAREST) {
            this.filterState = FilterState.NEAREST;
            RenderSystem.nearestFilter();
        }

    }

    public void deleteGlTexture() {
        if (this.glTextureId != -1) {
            TextureUtil.deleteTexture(this.glTextureId);
            this.glTextureId = -1;
        }
    }

    public void bindTexture() {

        if (this.getGlTextureId() == -1) {
            return;
        }

        GL11.glBindTexture(GL11.GL_TEXTURE_2D, this.getGlTextureId());

    }

    /**
     * 删除底层纹理对象，并把 {@link #glTextureId} 置回 -1。
     *
     * <p><b>1.20.1 移植关键点</b>：原实现删完之后仍保留旧的纹理名，靠下一次
     * {@code glBindTexture(GL_TEXTURE_2D, 旧名字)} 让驱动"隐式重建"这个对象——那是
     * OpenGL <em>compatibility</em> profile 的行为。MC 1.20.1 的上下文是 3.2 core，
     * 绑定一个不是 glGenTextures 产生的名字直接是 {@code GL_INVALID_OPERATION:
     * Texture name does not refer to a texture object generated by OpenGL}，
     * 后续上传全部丢弃。实测表现为播放器首页的歌单封面全是纯黑块，日志刷同一条错误。
     * 置回 -1 之后 {@link #getGlTextureId()} 会重新 glGenTextures 拿一个合法名字。
     *
     * <p>另外原来的 {@code if (getGlTextureId() == -1) return;} 是死代码：
     * {@code getGlTextureId()} 本身会在 -1 时顺手生成一个，永远不可能返回 -1。
     * 这里改成直接判字段，避免"为了删除而先创建一个纹理"。
     */
    public void deleteTexture() {

        final int textureId = this.glTextureId;
        if (textureId == -1) {
            return;
        }
        this.glTextureId = -1;

        if (MuoniumPlayerExtension.isCallingFromMainThread()) {
            api.getGLStateManager().deleteTexture(textureId);
        } else {
            MultiThreadingUtil.runOnMainThreadBlocking(() -> {
                GL11.glDeleteTextures(textureId);
                return null;
            });
        }

    }
}
